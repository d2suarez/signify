import { prisma } from "./db";
import { saveAttachments } from "./files";
import { APP_URL, notifyNewTicket, notifyTeamOfReply, sendMail } from "./mail";
import { notifyUsers } from "./notify";

const IMAP_HOST = process.env.IMAP_HOST || "imap.gmail.com";
const IMAP_USER = process.env.IMAP_USER || process.env.SMTP_USER;
const IMAP_PASS = process.env.IMAP_PASS || process.env.SMTP_PASS;
const POLL_SECONDS = Math.max(30, Number(process.env.EMAIL_INGEST_INTERVAL || 90));
const MAX_BODY = 5000;

export const ingestEnabled = Boolean(IMAP_USER && IMAP_PASS);

export type IncomingEmail = {
  fromAddress: string;
  fromName: string;
  subject: string;
  text: string;
  autoGenerated: boolean;
  attachments: { filename: string; contentType: string; content: Buffer }[];
};

/** Cut quoted reply history and signatures out of an email body. */
export function cleanEmailBody(text: string): string {
  let body = text.replace(/\r\n/g, "\n");
  const cutPatterns = [
    /^On .{0,200}wrote:\s*$/m,
    /^-{2,}\s*Original Message\s*-{2,}/im,
    /^_{10,}\s*$/m,
    /^From:\s.+$/m,
  ];
  for (const pattern of cutPatterns) {
    const match = body.search(pattern);
    if (match > 0) body = body.slice(0, match);
  }
  // Drop fully-quoted trailing lines
  const lines = body.split("\n");
  while (lines.length > 0 && (lines[lines.length - 1].startsWith(">") || lines[lines.length - 1].trim() === "")) {
    lines.pop();
  }
  return lines.join("\n").trim().slice(0, MAX_BODY);
}

function attachmentFiles(email: IncomingEmail): File[] {
  return email.attachments.map(
    (att) =>
      new File([new Uint8Array(att.content)], att.filename || "attachment", {
        type: att.contentType || "application/octet-stream",
      })
  );
}

/**
 * Turn one parsed email into a ticket (or a reply on an existing ticket).
 * Returns a short outcome string for logging/testing.
 */
export async function processIncomingEmail(email: IncomingEmail): Promise<string> {
  const from = email.fromAddress.toLowerCase();
  if (!from || email.autoGenerated) return "skipped:auto";
  if (/mailer-daemon|no-?reply|postmaster/i.test(from)) return "skipped:system";

  const subject = email.subject.trim();
  const body = cleanEmailBody(email.text);

  // Reply to an existing ticket? Notification subjects carry "#<id>".
  const refMatch = subject.match(/#(\d+)/);
  if (refMatch) {
    const ticket = await prisma.ticket.findUnique({ where: { id: Number(refMatch[1]) } });
    if (ticket && ticket.requesterEmail.toLowerCase() === from) {
      await prisma.comment.create({
        data: {
          ticketId: ticket.id,
          authorName: ticket.requesterName,
          body: body || "(empty email)",
          internal: false,
        },
      });
      const reopened = ["RESOLVED", "CLOSED"].includes(ticket.status);
      await prisma.ticket.update({
        where: { id: ticket.id },
        data: reopened ? { status: "OPEN", resolvedAt: null } : { updatedAt: new Date() },
      });
      try {
        await saveAttachments(ticket.id, attachmentFiles(email));
      } catch (error) {
        console.error("Email attachment save failed:", error);
      }
      await notifyTeamOfReply(ticket, body);
      const targets = ticket.assignedToId
        ? await prisma.user.findMany({ where: { id: ticket.assignedToId, active: true } })
        : await prisma.user.findMany({ where: { active: true, role: { in: ["ADMIN", "TECH"] } } });
      await notifyUsers(targets, "reply", {
        title: `Reply on #${ticket.id}`,
        body: `${ticket.requesterName}: ${body.slice(0, 200)}`,
        url: `/dashboard/tickets/${ticket.id}`,
      });
      return `reply:${ticket.id}`;
    }
  }

  // New ticket — the sender must be someone who has signed in to the help
  // desk with Signify ID, so we know who they are.
  const user = await prisma.user.findUnique({ where: { email: from } });
  if (user && !user.active) return "skipped:deactivated";
  if (!user) {
    await sendMail(
      from,
      "Please use the help desk site",
      `This inbox only accepts requests from people who have signed in to the help desk.\n\nSubmit your request here instead:\n${APP_URL}`
    );
    return "skipped:unknown-sender";
  }

  const ticket = await prisma.ticket.create({
    data: {
      title: subject.slice(0, 120) || "Email request",
      description: body,
      category: "OTHER",
      priority: "NORMAL",
      source: "EMAIL",
      requesterId: user.id,
      requesterName: user.name,
      requesterEmail: user.email,
      requesterRole: user.role === "STUDENT" ? "STUDENT" : "STAFF",
    },
  });
  try {
    await saveAttachments(ticket.id, attachmentFiles(email));
  } catch (error) {
    console.error("Email attachment save failed:", error);
  }

  await sendMail(
    user.email,
    `[#${ticket.id}] We got your request: ${ticket.title}`,
    `Thanks, ${user.name} — your request is in as ticket #${ticket.id}.\n\n` +
      `Track it or add details here:\n${APP_URL}/t/${ticket.token}\n\n` +
      `(You can also just reply to this email.)`
  );
  await notifyNewTicket(ticket);
  await notifyUsers(
    await prisma.user.findMany({ where: { active: true, role: { in: ["ADMIN", "TECH"] } } }),
    "new_ticket",
    {
      title: `New request #${ticket.id} (email)`,
      body: `${user.name}: ${ticket.title}`,
      url: `/dashboard/tickets/${ticket.id}`,
    }
  );
  return `created:${ticket.id}`;
}

/* ---------- IMAP polling ---------- */

let started = false;
let polling = false;

async function poll() {
  if (polling) return;
  polling = true;
  try {
    const { ImapFlow } = await import("imapflow");
    const { simpleParser } = await import("mailparser");

    const client = new ImapFlow({
      host: IMAP_HOST,
      port: 993,
      secure: true,
      auth: { user: IMAP_USER!, pass: IMAP_PASS! },
      logger: false,
    });
    await client.connect();
    const lock = await client.getMailboxLock("INBOX");
    try {
      const unseen = await client.search({ seen: false });
      const uids = Array.isArray(unseen) ? unseen : [];
      for (const uid of uids.slice(0, 20)) {
        const message = await client.fetchOne(String(uid), { source: true });
        if (!message || !("source" in message) || !message.source) continue;
        const parsed = await simpleParser(message.source);
        const autoHeader = parsed.headers.get("auto-submitted");
        const outcome = await processIncomingEmail({
          fromAddress: parsed.from?.value?.[0]?.address ?? "",
          fromName: parsed.from?.value?.[0]?.name ?? "",
          subject: parsed.subject ?? "",
          text: parsed.text ?? "",
          autoGenerated: Boolean(autoHeader && String(autoHeader) !== "no"),
          attachments: (parsed.attachments ?? []).map((att) => ({
            filename: att.filename ?? "attachment",
            contentType: att.contentType ?? "application/octet-stream",
            content: att.content,
          })),
        });
        await client.messageFlagsAdd(String(uid), ["\\Seen"]);
        console.log(`Email-to-ticket: ${outcome}`);
      }
    } finally {
      lock.release();
      await client.logout().catch(() => {});
    }
  } catch (error) {
    console.error(
      "Email ingest failed:",
      error instanceof Error ? error.message : error
    );
  } finally {
    polling = false;
  }
}

export function startEmailIngestion() {
  if (started) return;
  started = true;
  if (!ingestEnabled) {
    console.log("Email-to-ticket: disabled (set IMAP_USER/IMAP_PASS or SMTP_USER/SMTP_PASS to enable)");
    return;
  }
  console.log(`Email-to-ticket: polling ${IMAP_HOST} as ${IMAP_USER} every ${POLL_SECONDS}s`);
  setTimeout(poll, 10_000);
  setInterval(poll, POLL_SECONDS * 1000);
}
